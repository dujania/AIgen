export function similarJobs(job: Job, limit = 3): Job[] {
  return SAMPLE_JOBS.filter((j) => j.id !== job.id)
    .map((j) => {
      let score = 0;
      if (j.category === job.category) score += 2;
      if (j.mode === job.mode) score += 1;
      if (j.level === job.level) score += 1;
      score += j.skills.filter((s) => job.skills.includes(s)).length;
      return { j, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.j);
}
